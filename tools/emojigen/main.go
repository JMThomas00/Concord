// Command emojigen builds internal/emoji's table: every emoji a picker
// offers, in Unicode's order and groups, with its name, search keywords,
// GitHub :shortcodes: and skin-tone versions.
//
// Sources, pinned so a rerun gives the same table:
//   - Unicode's emoji-test.txt (Emoji 15.0, the newest Windows' Segoe UI
//     Emoji draws): order, groups, names and the skin-tone variants;
//   - CLDR's English annotations (44.1): the keywords search matches;
//   - github.com/yuin/goldmark-emoji (a dependency already, through
//     glamour): GitHub's shortcodes, read from its source because the
//     package can't list its emoji.
//
//	go run ./tools/emojigen                       # download, regenerate internal/emoji/data_gen.go
//	go run ./tools/emojigen -src <dir>            # use emoji-test.txt, annotations.json, annotationsDerived.json from dir
package main

import (
	"bufio"
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

const (
	emojiVersion = "15.0"
	cldrVersion  = "44.1.0"
	testURL      = "https://unicode.org/Public/emoji/" + emojiVersion + "/emoji-test.txt"
	annURL       = "https://raw.githubusercontent.com/unicode-org/cldr-json/" + cldrVersion + "/cldr-json/cldr-annotations-full/annotations/en/annotations.json"
	derivedURL   = "https://raw.githubusercontent.com/unicode-org/cldr-json/" + cldrVersion + "/cldr-json/cldr-annotations-derived-full/annotationsDerived/en/annotations.json"
)

// The picker's groups, in emoji-test.txt's order; "Component" (bare skin
// tones and hair styles) isn't offered.
var groups = []string{"Smileys & Emotion", "People & Body", "Animals & Nature", "Food & Drink",
	"Travel & Places", "Activities", "Objects", "Symbols", "Flags"}

type entry struct {
	char, name string
	group      int
	keywords   []string
	shortcodes []string
	tones      [5]string
}

func main() {
	src := flag.String("src", "", "folder holding the three source files (default: download them)")
	out := flag.String("out", "internal/emoji/data_gen.go", "file to write")
	flag.Parse()

	test := read(*src, "emoji-test.txt", testURL)
	ann := annotations(read(*src, "annotations.json", annURL))
	for k, v := range annotations(read(*src, "annotationsDerived.json", derivedURL)) {
		if _, ok := ann[k]; !ok {
			ann[k] = v
		}
	}
	codes := shortcodes()

	var list []*entry
	byBase := map[string]*entry{}
	group := -1
	sc := bufio.NewScanner(bytes.NewReader(test))
	line := regexp.MustCompile(`^([0-9A-F ]+?)\s*; fully-qualified\s*# (\S+) E\d+\.\d+ (.+)$`)
	for sc.Scan() {
		t := sc.Text()
		if g, ok := strings.CutPrefix(t, "# group: "); ok {
			group = index(groups, g)
			continue
		}
		m := line.FindStringSubmatch(t)
		if m == nil || group < 0 {
			continue
		}
		char := fromHex(m[1])
		if tone, base, ok := toned(char); ok {
			if e := byBase[strip(base)]; e != nil && e.tones[tone] == "" {
				e.tones[tone] = char
			}
			continue
		}
		e := &entry{char: char, name: m[3], group: group}
		a := ann[char]
		if a == nil {
			a = ann[strings.ReplaceAll(char, "️", "")]
		}
		for _, k := range a {
			if k = strings.ToLower(k); k != strings.ToLower(e.name) && index(e.keywords, k) < 0 {
				e.keywords = append(e.keywords, k)
			}
		}
		e.shortcodes = codes[strip(char)]
		list = append(list, e)
		byBase[strip(char)] = e
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/emojigen from Unicode Emoji %s, CLDR %s and\n", emojiVersion, cldrVersion)
	b.WriteString("// GitHub's shortcodes (goldmark-emoji). DO NOT EDIT.\n\npackage emoji\n\n")
	fmt.Fprintf(&b, "// UnicodeVersion is the Emoji version the table comes from.\nconst UnicodeVersion = %q\n\n", emojiVersion)
	b.WriteString("// GroupNames are the picker's groups, in order (Emoji.Group indexes it).\nvar GroupNames = []string{")
	for i, g := range groups {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q", g)
	}
	b.WriteString("}\n\n// table is one emoji per line: emoji, group, name, shortcodes (space),\n// keywords (|), skin-tone versions (space; light to dark, or empty).\nconst table = `")
	tones := 0
	for _, e := range list {
		for _, f := range append([]string{e.name}, e.keywords...) {
			if strings.ContainsAny(f, "\t|`\n") {
				log.Fatalf("%s: a field holds a separator: %q", e.char, f)
			}
		}
		t := ""
		if e.tones[0] != "" && e.tones[4] != "" {
			t = strings.Join(e.tones[:], " ")
			tones++
		}
		fmt.Fprintf(&b, "%s\t%d\t%s\t%s\t%s\t%s\n", e.char, e.group, e.name, strings.Join(e.shortcodes, " "), strings.Join(e.keywords, "|"), t)
	}
	b.WriteString("`\n")
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote %s: %d emoji, %d with skin tones\n", *out, len(list), tones)
}

// toned splits a skin-toned emoji into its tone (0 light ... 4 dark) and
// its untoned form. ok is false for an emoji without a tone, or one mixing
// tones (two people of different tones aren't offered as a tone choice).
func toned(s string) (tone int, base string, ok bool) {
	tone = -1
	var b strings.Builder
	for _, r := range s {
		if r >= 0x1F3FB && r <= 0x1F3FF {
			t := int(r - 0x1F3FB)
			if tone >= 0 && tone != t {
				return 0, "", false
			}
			tone = t
			continue
		}
		b.WriteRune(r)
	}
	return tone, b.String(), tone >= 0
}

// strip drops variation selectors, so "☝️" and "☝" (and a tone variant's
// base) compare equal.
func strip(s string) string { return strings.ReplaceAll(s, "️", "") }

func fromHex(s string) string {
	var b strings.Builder
	for _, h := range strings.Fields(s) {
		v, err := strconv.ParseUint(h, 16, 32)
		if err != nil {
			log.Fatalf("bad code point %q", h)
		}
		b.WriteRune(rune(v))
	}
	return b.String()
}

func index(list []string, s string) int {
	for i, v := range list {
		if v == s {
			return i
		}
	}
	return -1
}

func read(dir, name, url string) []byte {
	if dir != "" {
		b, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			log.Fatal(err)
		}
		return b
	}
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: HTTP %d", url, resp.StatusCode)
	}
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	return b
}

// annotations maps each emoji to its CLDR keywords and spoken name.
func annotations(data []byte) map[string][]string {
	var doc struct {
		Annotations struct {
			Annotations map[string]struct {
				Default []string `json:"default"`
				TTS     []string `json:"tts"`
			} `json:"annotations"`
		} `json:"annotations"`
	}
	if err := json.Unmarshal(data, &doc); err != nil {
		log.Fatal(err)
	}
	out := map[string][]string{}
	for k, v := range doc.Annotations.Annotations {
		out[k] = append(append([]string{}, v.TTS...), v.Default...)
	}
	return out
}

// shortcodes reads GitHub's shortcodes out of goldmark-emoji's source:
// lines like NewEmoji("grinning face", []int32{128512}, "grinning").
func shortcodes() map[string][]string {
	dir, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "github.com/yuin/goldmark-emoji").Output()
	if err != nil {
		log.Fatalf("finding goldmark-emoji: %v", err)
	}
	src, err := os.ReadFile(filepath.Join(strings.TrimSpace(string(dir)), "definition", "github.go"))
	if err != nil {
		log.Fatal(err)
	}
	re := regexp.MustCompile(`NewEmoji\("[^"]*", \[\]int32\{([0-9, ]*)\}((?:, "[^"]+")+)\)`)
	out := map[string][]string{}
	for _, m := range re.FindAllStringSubmatch(string(src), -1) {
		var b strings.Builder
		for _, n := range strings.Split(m[1], ",") {
			if v, err := strconv.Atoi(strings.TrimSpace(n)); err == nil {
				b.WriteRune(rune(v))
			}
		}
		var names []string
		for _, q := range regexp.MustCompile(`"([^"]+)"`).FindAllStringSubmatch(m[2], -1) {
			names = append(names, q[1])
		}
		sort.SliceStable(names, func(i, j int) bool { return len(names[i]) < len(names[j]) })
		out[strip(b.String())] = names
	}
	return out
}
